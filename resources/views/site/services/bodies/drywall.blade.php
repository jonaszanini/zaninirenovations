<h2>Drywall services</h2>

<p><strong>New walls and ceilings.</strong> Hanging drywall on new framing in basements, additions, closets and bump-outs, including bulkheads around ducts and beams.</p>

<p><strong>Taping, mudding and sanding.</strong> Taping joints, setting corner bead and building up coats of compound, then sanding to a smooth, paint-ready finish. In Perth, before building a custom fireplace mantel, we taped, mudded and sanded the surrounding wall so the paint would go on flawlessly.</p>

<p><strong>Feature walls and fireplace bump-outs.</strong> Drywall is often the base for a finished feature. In a Carleton Place living room we built a clean drywall bump-out around a fireplace with a recessed niche, then trimmed it with a wood sill and wrapped baseboard.</p>

<p><strong>Flood and leak repairs.</strong> After water damage, the wet drywall has to come out. In a Carleton Place basement we installed a 2 foot flood cut of new drywall through two rooms and a hallway. We taped and sanded it so it blends with the existing upper walls, and the new trim covered the bottom edge.</p>

<p><strong>Smaller repairs.</strong> Holes, cracks, patches after a wall has been opened for wiring or pipes, and damaged corners. Send photos of your repair and we'll let you know how we can help.</p>

<h2>Finish level and ceilings</h2>

<p>Not every wall needs the same finish. A garage or utility room can stop at a basic taped finish, while a living room with big windows and raking light needs more coats and careful sanding to hide every joint. We'll agree on the finish for each area before we start, so there are no surprises when the paint goes on.</p>

<h2>Dust control and cleanup</h2>

<p>Sanding drywall makes fine dust that gets everywhere if nobody manages it. Before the job starts, we'll talk about how the work area will be closed off and kept clean. We keep the work area organized and clean it up at the end, so you're not living in a construction site.</p>

<h2>How a drywall job works</h2>
<ol>
  <li><strong>Look at the space.</strong> We check the framing, the size of the area, and any water damage or open wall cavities.</li>
  <li><strong>Written estimate</strong> in Canadian dollars, labour-only or with materials.</li>
  <li><strong>Prep.</strong> For repairs, damaged material comes out and the source of any water has to be fixed first. Insulation, vapour barrier and any required inspections come before boarding.</li>
  <li><strong>Hang, tape and finish.</strong> Drywall compound needs drying time between coats, which is the main thing that sets the schedule.</li>
  <li><strong>Prime and paint</strong>, if we've agreed on it in the quote.</li>
  <li><strong>Cleanup.</strong></li>
</ol>

