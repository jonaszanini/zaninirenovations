<h2>Preparation decides how the floor lasts</h2>

<p>Most flooring problems trace back to what's underneath, so good prep usually involves:</p>
<ul>
  <li><strong>Taking out the old flooring</strong>: carpet, pad, staples or old planks.</li>
  <li><strong>Checking the subfloor</strong> for flatness, squeaks and loose spots, and fixing them before anything goes on top.</li>
  <li><strong>Levelling where needed</strong>, because many floors need a flat base to perform well.</li>
  <li><strong>The right underlay</strong> for the product and the room, following the flooring manufacturer's instructions.</li>
  <li><strong>Acclimating the material</strong> as the manufacturer specifies.</li>
</ul>

<p>We'll go over what your floor needs at the estimate.</p>

