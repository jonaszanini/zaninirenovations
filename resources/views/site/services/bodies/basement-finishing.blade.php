<h2>What a basement finish involves</h2>

<p><strong>Framing.</strong> Exterior walls framed in front of the foundation, interior walls for rooms and closets, and bulkheads boxed around ducts, beams and pipes.</p>

<p><strong>Insulation and vapour barrier.</strong> The foundation walls need to be insulated and protected properly before anything gets closed in. It's the step that makes the biggest difference to how warm the room feels in winter.</p>

<p><strong>Drywall.</strong> Hanging, taping, mudding and sanding walls and ceilings to a smooth, paint-ready finish. More on our <a href="{{ url('/services/drywall') }}">drywall page</a>.</p>

<p><strong>Flooring</strong> suited to a concrete slab, such as vinyl plank, engineered wood, laminate or tile. See <a href="{{ url('/services/flooring-installation') }}">flooring installation</a> for the options.</p>

<p><strong>Doors, trim and closets.</strong> Interior doors, sliding barn doors where swing space is tight, closet doors, casings, baseboards and shoe moulding. See <a href="{{ url('/services/finish-carpentry-trim') }}">finish carpentry and trim</a>.</p>

<p><strong>Built-ins.</strong> Shelving, desk nooks, media walls and storage under the stairs, built to fit the room. See <a href="{{ url('/services/custom-built-ins-closets') }}">custom built-ins and closets</a>.</p>

<h2>What other trades handle</h2>

<p>Electrical and plumbing work has to be done by qualified, certified trades. That includes outlets, pot lights, and the drains and supply lines for a basement bathroom or wet bar. We arrange qualified, certified electricians and plumbers as part of your project and schedule their work around ours, so you don't have to find them yourself. Structural changes, like removing a post or enlarging a window opening, are a separate discussion and may need an engineer.</p>

<h2>Permits and inspections</h2>

<p>Finishing a basement often needs a building permit, and permitted work comes with inspections before walls are closed in. Rules are set locally: the City of Ottawa has its own guidance for finishing a basement, while Carleton Place, Mississippi Mills, Beckwith and Perth each run their own building departments. We can help with the permit application as an optional add-on, quoted separately, or you're welcome to handle the permit yourself. Our work in Ontario is done to the Ontario Building Code (O.Reg. 332/12).</p>

<h2>Moisture comes first</h2>

<p>We won't frame over a wet wall. Before planning a layout, we check for signs of water: stains, white chalky deposits on the concrete, a musty smell, or damp spots after rain or the spring thaw. If there's a source, such as grading, downspouts, a crack or the sump, it needs fixing first. Once the space is dry, we'll talk through how the walls and floor should be put together for your basement.</p>

<h2>Rebuilding after a flood</h2>

<p>When water has already done damage, the job is part repair, part finishing. In a Carleton Place basement we cut out the damaged drywall and replaced a 2 foot flood cut through two rooms and a hallway. We taped and sanded it to blend with the upper walls, then installed new door trim, baseboards, shoe moulding and flooring throughout. If the repair is part of an insurance claim, mention it when you get in touch.</p>

