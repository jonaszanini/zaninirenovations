<h2>Choosing your decking material</h2>

<p>There's no single best board. Each material trades upfront cost against upkeep:</p>
<ul>
  <li><strong>Pressure-treated lumber</strong> is the budget-friendly, most common choice. It needs regular staining and can crack or warp as it weathers.</li>
  <li><strong>Cedar</strong> has natural oils that resist rot and insects and a warm, natural look, but it is soft, scratches easily and turns silvery grey if left untreated.</li>
  <li><strong>Capped composite</strong> costs more upfront but needs far less maintenance. It is less stiff than wood, so we plan closer joist spacing into the frame.</li>
  <li><strong>Solid PVC</strong> is the premium synthetic option with the most moisture resistance. It moves more with heat, so the framing needs extra care.</li>
</ul>

<p>Our <a href="{{ url('/blog/the-ultimate-decking-showdown-pressure-treated-vs-cedar-vs-composite-vs-pvc') }}">decking showdown</a> compares all four in detail, including slip, flex and heat tests. On wood decks, hidden side fasteners can help the boards last longer because there are no screw holes in the face for water to sit in.</p>

<p>Railings finish a deck and keep it safe. We'll go through railing styles and materials at the estimate and pick what suits your deck and your house.</p>

<h2>Footings, framing and permits</h2>

<p>A deck is only as good as what's underneath it: solid footings, proper connectors and hangers, and framing protected where moisture collects. The frame is the part you never see once the boards are down, so it's where we take the most care. Our work in Ontario is done to the Ontario Building Code (O.Reg. 332/12).</p>

<p>Whether your deck needs a building permit depends on its height, size and whether it attaches to the house, and every municipality sets its own rules. The City of Ottawa, the Town of Carleton Place, Mississippi Mills, Beckwith and Perth each have their own building department, so it's worth checking early. We can help with the permit application as an optional add-on, quoted separately, or you're welcome to handle the permit yourself.</p>

<p>Call before you dig: utility locates are required before any footing or post hole goes in. In Ontario, locates are requested through Ontario One Call.</p>

